export interface DropdownItem {
  label: string;
  onClick: () => void;
  icon?: React.ComponentType<any>;
  danger?: boolean;
  disabled?: boolean;
  title?: string;
}

export interface CustomDropdownMenuProps {
  trigger: React.ReactElement<{ onClick?: React.MouseEventHandler<HTMLElement>; ref?: React.Ref<HTMLElement> }>;
  items: DropdownItem[];
  align?: "left" | "right";
}

function CustomPortalDropdownMenu({
  trigger,
  items,
  align = "right",
}: CustomDropdownMenuProps) {
  const [isOpen, setIsOpen] = React.useState(false);
  const triggerRef = React.useRef<HTMLElement | null>(null);
  const dropdownRef = React.useRef<HTMLDivElement | null>(null);
  const [coords, setCoords] = React.useState({ top: 0, left: 0 });

  const toggleMenu = (e: React.MouseEvent) => {
    e.stopPropagation();
    const rect = (e.currentTarget as HTMLElement).getBoundingClientRect();

    setCoords({
      top: rect.bottom + window.scrollY + 4,
      left: align === "right"
        ? rect.right + window.scrollX
        : rect.left + window.scrollX,
    });
    setIsOpen((prev) => !prev);
  };

  React.useEffect(() => {
    if (!isOpen) return;

    const handleClickOutside = (event: MouseEvent) => {
      const target = event.target as Node;
      if (
        dropdownRef.current &&
        !dropdownRef.current.contains(target) &&
        triggerRef.current &&
        !triggerRef.current.contains(target)
      ) {
        setIsOpen(false);
      }
    };

    const handleScrollOrResize = () => {
      if (triggerRef.current) {
        const rect = triggerRef.current.getBoundingClientRect();
        setCoords({
          top: rect.bottom + window.scrollY + 4,
          left: align === "right"
            ? rect.right + window.scrollX
            : rect.left + window.scrollX,
        });
      }
    };

    document.addEventListener("mousedown", handleClickOutside);
    window.addEventListener("scroll", handleScrollOrResize, true);
    window.addEventListener("resize", handleScrollOrResize);

    return () => {
      document.removeEventListener("mousedown", handleClickOutside);
      window.removeEventListener("scroll", handleScrollOrResize, true);
      window.removeEventListener("resize", handleScrollOrResize);
    };
  }, [isOpen, align]);

  const triggerElement = React.cloneElement(trigger, {
    ref: (node: HTMLElement) => {
      triggerRef.current = node;
      const { ref: originalRef } = trigger as any;
      if (originalRef) {
        if (typeof originalRef === "function") {
          originalRef(node);
        } else if (originalRef.current) {
          originalRef.current = node;
        }
      }
    },
    onClick: (e: React.MouseEvent<HTMLElement>) => {
      if (trigger.props.onClick) {
        trigger.props.onClick(e);
      }
      toggleMenu(e);
    },
  });

  return (
    <>
      {triggerElement}
      {isOpen &&
        createPortal(
          <div
            ref={dropdownRef}
            style={{
              position: "absolute",
              top: `${coords.top}px`,
              left: `${coords.left}px`,
              transform: align === "right" ? "translateX(-100%)" : "none",
              zIndex: 9999,
            }}
            className="bg-white dark:bg-[#111625] rounded-xl shadow-lg border border-slate-100 dark:border-[#232D42] overflow-hidden py-1.5 min-w-[180px]"
          >
            {items.map((item, index) => {
              const Icon = item.icon;
              return (
                <button
                  key={index}
                  disabled={item.disabled}
                  title={item.title}
                  onClick={() => {
                    if (item.disabled) return;
                    item.onClick();
                    setIsOpen(false);
                  }}
                  className={`w-full flex items-center px-4 py-2.5 text-left text-sm select-none border-0 min-h-[44px] ${
                    item.disabled
                      ? "text-slate-300 dark:text-slate-600 bg-slate-50 dark:bg-[#0B0F19] cursor-not-allowed"
                      : item.danger
                      ? "text-[#BE123C] dark:text-rose-400 hover:bg-red-50/50 dark:hover:bg-rose-950/30 cursor-pointer"
                      : "text-slate-700 dark:text-[#F8FAFC] hover:bg-[#111184]/5 dark:hover:bg-[#171E2E] hover:text-[#FF4F00] dark:hover:text-[#FF4F00] cursor-pointer"
                  }`}
                >
                  {Icon && <Icon size={16} className="mr-3 shrink-0" />}
                  <span>{item.label}</span>
                </button>
              );
            })}
          </div>,
          document.body
        )}
    </>
  );
}

function DropdownMenu(props: any) {
  if (props && "trigger" in props && "items" in props) {
    return <CustomPortalDropdownMenu {...props} />;
  }
  return <DropdownMenuPrimitive.Root data-slot="dropdown-menu" {...props} />;
}

